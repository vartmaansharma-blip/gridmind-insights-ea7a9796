import { useEffect, useRef, useState } from "react";
import {
  Dialog,
  DialogContent,
  DialogTitle,
  DialogDescription,
  DialogTrigger,
} from "@/components/ui/dialog";
import { Button } from "@/components/ui/button";
import {
  assistantModes,
  explainSample,
  type AssistantMode,
  type Explanation,
} from "@/lib/assistant/explanation";
import type { SampleWorkspace } from "@/lib/sample/workspace";
import { RecordLink, EvidenceCard } from "./record-detail";
export function AskGridMind({ s, recordId }: { s: SampleWorkspace; recordId?: string }) {
  const [open, setOpen] = useState(false),
    [mode, setMode] = useState<AssistantMode>("Explain"),
    [question, setQuestion] = useState("What can this sample actually show?"),
    [answer, setAnswer] = useState<Explanation | null>(null),
    [busy, setBusy] = useState(false),
    [notice, setNotice] = useState("");
  const generation = useRef(0);
  const cancel = () => {
    generation.current++;
    setBusy(false);
  };
  useEffect(() => {
    generation.current++;
    setAnswer(null);
    setBusy(false);
    setNotice("");
  }, [s.sourceRevision, recordId]);
  useEffect(
    () => () => {
      generation.current++;
    },
    [],
  );
  async function ask() {
    const id = ++generation.current;
    setBusy(true);
    setAnswer(null);
    setNotice("");
    try {
      await new Promise<void>((resolve) => requestAnimationFrame(() => resolve()));
      const result = explainSample(s, recordId, mode, question);
      if (id === generation.current) setAnswer(result);
    } catch (error) {
      if (id === generation.current)
        setNotice(error instanceof Error ? error.message : "Explanation unavailable.");
    } finally {
      if (id === generation.current) setBusy(false);
    }
  }
  return (
    <Dialog
      open={open}
      onOpenChange={(value) => {
        setOpen(value);
        if (!value) cancel();
      }}
    >
      <DialogTrigger asChild>
        <Button variant="outline">Ask GridMind</Button>
      </DialogTrigger>
      <DialogContent className="max-h-[90dvh] w-[calc(100%-2rem)] max-w-2xl overflow-y-auto">
        <DialogTitle>Ask GridMind</DialogTitle>
        <DialogDescription>
          Deterministic sample explanation · SYNTHETIC · Not generated by Claude. No paid API or
          private records are used.
        </DialogDescription>
        <p className="text-xs break-words">
          {s.profile.organization} / {s.profile.factory} / {recordId ?? "workspace"} / input
          revision {s.sourceRevision}
        </p>
        <form
          className="space-y-3"
          onSubmit={(e) => {
            e.preventDefault();
            void ask();
          }}
        >
          <label className="block text-sm">
            Explanation mode
            <select
              value={mode}
              onChange={(e) => {
                cancel();
                setAnswer(null);
                setMode(e.target.value as AssistantMode);
              }}
              className="mt-1 block w-full rounded border bg-background p-2"
            >
              {assistantModes.map((m) => (
                <option key={m}>{m}</option>
              ))}
            </select>
          </label>
          <label className="block text-sm">
            Question
            <textarea
              required
              maxLength={600}
              value={question}
              onChange={(e) => setQuestion(e.target.value)}
              className="mt-1 block w-full rounded border bg-background p-2"
            />
          </label>
          <p className="text-xs text-muted-foreground">
            The fallback summarizes the current record and selected mode; it is not open-ended chat.
            Claude activation requires approved credentials, budget and server permission controls.
          </p>
          <div className="flex flex-wrap gap-2">
            <Button type="submit" variant="cta" disabled={busy || !question.trim()}>
              {busy ? "Preparing explanation…" : "Explain current context"}
            </Button>
            {busy && (
              <Button type="button" variant="outline" onClick={cancel}>
                Cancel explanation
              </Button>
            )}
            <Button
              type="button"
              variant="outline"
              onClick={() => {
                cancel();
                setAnswer(null);
                setNotice("");
                setQuestion("What can this sample actually show?");
              }}
            >
              Reset explanation
            </Button>
          </div>
        </form>
        {notice && <p role="status">{notice}</p>}
        <div aria-live="polite" aria-busy={busy}>
          {answer && (
            <article className="space-y-3 text-sm">
              <h3 className="font-semibold">What the records support</h3>
              <p>{answer.answer}</p>
              <h3 className="font-semibold">Assumptions and uncertainty</h3>
              <ul className="list-disc pl-5">
                {[...answer.assumptions, ...answer.uncertainty].map((text) => (
                  <li key={text}>{text}</li>
                ))}
              </ul>
              <p>
                <strong>Next action:</strong> {answer.nextStep}
              </p>
              <p>
                Human review required. A simulated decision provides no real operational authority.
              </p>
              <nav aria-label="Assistant related records" className="flex flex-wrap gap-3">
                {answer.recordIds.map((id) => (
                  <RecordLink key={id} s={s} id={id} />
                ))}
              </nav>
              <div className="space-y-2">
                {answer.evidenceIds.map((id) => (
                  <EvidenceCard key={id} s={s} id={id} />
                ))}
              </div>
              <Button
                variant="outline"
                onClick={async () => {
                  try {
                    await navigator.clipboard.writeText(JSON.stringify(answer, null, 2));
                    setNotice("Synthetic explanation copied.");
                  } catch {
                    setNotice("Clipboard unavailable. Select the explanation text to copy it.");
                  }
                }}
              >
                Copy synthetic explanation
              </Button>
            </article>
          )}
        </div>
      </DialogContent>
    </Dialog>
  );
}
