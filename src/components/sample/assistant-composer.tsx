import { useEffect, useId, useRef, type RefObject } from "react";
import { ArrowUp, ChevronDown, Layers, Square } from "lucide-react";
import { Button } from "@/components/ui/button";
import { assistantModes, type AssistantMode } from "@/lib/assistant/explanation";
type Props = {
  question: string;
  setQuestion: (value: string) => void;
  mode: AssistantMode;
  setMode: (value: AssistantMode) => void;
  busy: boolean;
  limited: boolean;
  unavailable: boolean;
  showContext: boolean;
  contextId: string;
  onContext: () => void;
  onAsk: () => void;
  onCancel: () => void;
  inputRef: RefObject<HTMLTextAreaElement | null>;
};
export function AssistantComposer({
  question,
  setQuestion,
  mode,
  setMode,
  busy,
  limited,
  unavailable,
  showContext,
  contextId,
  onContext,
  onAsk,
  onCancel,
  inputRef,
}: Props) {
  const id = useId(),
    helper = useId();
  const form = useRef<HTMLFormElement>(null);
  useEffect(() => {
    const input = inputRef.current;
    if (input) {
      input.style.height = "auto";
      input.style.height = `${Math.min(156, Math.max(78, input.scrollHeight))}px`;
    }
  }, [question, inputRef]);
  return (
    <form
      ref={form}
      className="gm-ai-composer-wrap"
      onSubmit={(e) => {
        e.preventDefault();
        onAsk();
      }}
    >
      <div className="gm-ai-composer">
        <label className="sr-only" htmlFor={id}>
          Question
        </label>
        <textarea
          id={id}
          ref={inputRef}
          rows={2}
          required
          disabled={unavailable}
          maxLength={600}
          value={question}
          placeholder="Ask about this order, machine or investigation…"
          aria-describedby={helper}
          enterKeyHint="send"
          onChange={(e) => setQuestion(e.target.value)}
          onKeyDown={(e) => {
            if (e.key === "Enter" && !e.shiftKey && !e.nativeEvent.isComposing) {
              e.preventDefault();
              if (question.trim() && !busy && !limited && !unavailable)
                form.current?.requestSubmit();
            }
          }}
        />
        <div className="gm-ai-toolbar">
          <Button
            type="button"
            variant="ghost"
            className="gm-ai-context-button"
            aria-label="Context"
            aria-expanded={showContext}
            aria-controls={contextId}
            onClick={onContext}
          >
            <Layers aria-hidden="true" />
            <span>Context</span>
          </Button>
          <div className="gm-ai-mode">
            <label htmlFor={`${id}-mode`} className="sr-only">
              Explanation mode
            </label>
            <select
              id={`${id}-mode`}
              value={mode}
              onChange={(e) => setMode(e.target.value as AssistantMode)}
              disabled={busy || unavailable}
            >
              {assistantModes.map((m) => (
                <option key={m}>{m}</option>
              ))}
            </select>
            <ChevronDown aria-hidden="true" />
          </div>
          <span className="gm-ai-character-count num">{question.length}/600</span>
          {busy ? (
            <Button
              type="button"
              variant="cta"
              className="gm-ai-send"
              aria-label="Cancel explanation"
              title="Cancel explanation"
              onClick={onCancel}
            >
              <Square aria-hidden="true" />
            </Button>
          ) : (
            <Button
              type="submit"
              variant="cta"
              className="gm-ai-send"
              disabled={!question.trim() || limited || unavailable}
              aria-label="Explain current context"
              title="Explain current context"
            >
              <ArrowUp aria-hidden="true" />
            </Button>
          )}
        </div>
      </div>
      <div id={helper} className="gm-ai-composer-caption">
        <span>
          {unavailable
            ? "Open an available record to continue."
            : limited
              ? "Six explanations reached. Start a new conversation to continue."
              : "Context summary, not open-ended AI. Not generated by Claude."}
        </span>
        <span className="gm-ai-key-hint">Enter to send · Shift+Enter for a new line</span>
      </div>
    </form>
  );
}
